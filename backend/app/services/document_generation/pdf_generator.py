import os
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable
from app.core.config import settings

OUTPUT_DIR = os.path.join(settings.DOCUMENT_UPLOAD_DIR, "generated_docs")
os.makedirs(OUTPUT_DIR, exist_ok=True)


def generate_pdf(document_id: str, title: str, content: str) -> str:
    """Generate a clean, printable PDF legal draft using ReportLab."""
    file_path = os.path.join(OUTPUT_DIR, f"{document_id}.pdf")
    doc = SimpleDocTemplate(
        file_path,
        pagesize=letter,
        rightMargin=54,
        leftMargin=54,
        topMargin=54,
        bottomMargin=54
    )

    styles = getSampleStyleSheet()
    
    title_style = ParagraphStyle(
        'LegalTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=15,
        leading=18,
        textColor=colors.HexColor('#102a43'),
        alignment=1,  # Center
        spaceAfter=6
    )

    subtitle_style = ParagraphStyle(
        'LegalSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=8,
        leading=10,
        textColor=colors.HexColor('#627d98'),
        alignment=1,  # Center
        spaceAfter=14
    )

    heading_style = ParagraphStyle(
        'LegalHeading',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=11,
        leading=14,
        textColor=colors.HexColor('#102a43'),
        spaceBefore=10,
        spaceAfter=4
    )

    body_style = ParagraphStyle(
        'LegalBody',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        leading=14,
        textColor=colors.HexColor('#243b53'),
        spaceAfter=6
    )

    disclaimer_style = ParagraphStyle(
        'LegalDisclaimer',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor('#829ab1'),
        spaceBefore=12,
        spaceAfter=8
    )

    story = [
        Paragraph(f"LEGAL DRAFT: {title.upper()}", title_style),
        Paragraph("Educational Legal Draft Generated by LegalAI • Verification Required", subtitle_style),
        HRFlowable(width="100%", thickness=1, color=colors.HexColor('#bcccdc'), spaceAfter=14)
    ]

    lines = content.split("\n")
    for line in lines:
        stripped = line.strip()
        if not stripped:
            story.append(Spacer(1, 6))
            continue

        safe_text = stripped.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

        if "DISCLAIMER" in stripped:
            story.append(Paragraph(safe_text, disclaimer_style))
        elif stripped.isupper() and len(stripped) < 80:
            story.append(Paragraph(safe_text, heading_style))
        else:
            story.append(Paragraph(safe_text, body_style))

    doc.build(story)
    return file_path
